#!/bin/sh
# Builds the Ridgun runtime for wasm32 (ADR-0013) and writes it as the
# generated module src/main/ridgun/lib/wasmrt.ridgun, which the wasm backend
# links into every program. Needs llvm-link, opt, llc and wasm-ld (LLVM 19).
# Run from the repository root: sh src/main/runtime/build-wasm32.sh
set -eu
here=$(dirname "$0")
out=src/main/ridgun/lib/wasmrt.ridgun
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

llvm-link "$here"/core/*.ll "$here"/pal/wasm32.ll -o "$tmp/rt.bc"
opt -O2 -mtriple=wasm32-unknown-unknown "$tmp/rt.bc" -o "$tmp/rt.opt.bc"
llc -O2 -mtriple=wasm32-unknown-unknown -filetype=obj "$tmp/rt.opt.bc" -o "$tmp/rt.o"
wasm-ld --no-entry --export-dynamic --stack-first -z stack-size=8388608 \
  --export=__heap_base --export=__stack_pointer --export-table --growable-table \
  "$tmp/rt.o" -o "$tmp/rt.wasm"

size=$(wc -c < "$tmp/rt.wasm")
{
  echo "-- ============================================================"
  echo "-- src/main/ridgun/lib/wasmrt.ridgun"
  echo "-- GENERATED by src/main/runtime/build-wasm32.sh from src/main/runtime/"
  echo "-- (ADR-0013). Do not edit: change the IR and run the script again."
  echo "-- The Ridgun runtime as a linked wasm32 module ($size bytes), in hex."
  echo "-- ============================================================"
  echo ""
  echo "fn :: wasm rt module hex => [String]"
  printf '      wasm rt module hex =  ['
  printf '%s]\n' "$(od -An -tx1 -v "$tmp/rt.wasm" | tr -d ' \n' | fold -w 4096 | sed 's/.*/"&"/' | paste -sd, - | sed 's/,/, /g')"
} > "$out"
echo "wrote $out ($size bytes of wasm)"

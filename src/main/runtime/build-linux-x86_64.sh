#!/bin/sh
# Builds the Ridgun runtime for Linux on x86-64 (ADR-0013, TASK-0096) as one
# position-independent object: core + the Linux PAL + the entry points of the
# LLVM backend's helpers. Needs llvm-link, opt and llc (LLVM 19).
# Run from the repository root:
#   sh src/main/runtime/build-linux-x86_64.sh [out.o]
#   sh src/main/runtime/build-linux-x86_64.sh --module
#   sh src/main/runtime/build-linux-x86_64.sh --flat
# With --module it writes src/main/ridgun/lib/x86rt.ridgun, the object as hex
# in a generated module that the LLVM backend links into every program.
# With --flat it writes src/main/ridgun/lib/x86flat.ridgun: the same runtime
# linked at a fixed address as a flat image for the pure x86-64 encoder.
set -eu
here=$(dirname "$0")
module=no
flat=no
if [ "${1:-}" = "--module" ]; then module=yes; shift; fi
if [ "${1:-}" = "--flat" ]; then flat=yes; shift; fi
out=${1:-/tmp/ridgun-rt-linux-x86_64.o}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
llvm-link "$here"/core/*.ll "$here"/abi/llvm.ll "$here"/posix/posix.ll "$here"/pal/linux-x86_64.ll -o "$tmp/rt.bc"
opt -O2 -mtriple=x86_64-unknown-linux-gnu "$tmp/rt.bc" -o "$tmp/rt.opt.bc"
llc -O2 -mtriple=x86_64-unknown-linux-gnu -relocation-model=pic -filetype=obj "$tmp/rt.opt.bc" -o "$out"
# A symbol the runtime needs but no file defines would become address 0 in
# the program: stop here instead.
undefined=$(nm "$out" | grep " U " || true)
if [ -n "$undefined" ]; then
  echo "undefined symbols in the runtime:" >&2
  echo "$undefined" >&2
  exit 1
fi
if [ "$module" = yes ]; then
  mod=src/main/ridgun/lib/x86rt.ridgun
  size=$(wc -c < "$out")
  id=$(cksum < "$out" | cut -d' ' -f1)
  {
    echo "-- ============================================================"
    echo "-- src/main/ridgun/lib/x86rt.ridgun"
    echo "-- GENERATED by src/main/runtime/build-linux-x86_64.sh --module from"
    echo "-- src/main/runtime/ (ADR-0013). Do not edit: change the IR and run the"
    echo "-- script again."
    echo "-- The Ridgun runtime for Linux on x86-64 as one relocatable object"
    echo "-- ($size bytes), in hex. The LLVM backend writes it to a cache file and"
    echo "-- links it with every program."
    echo "-- ============================================================"
    echo ""
    echo "fn :: x86 rt object id => Int"
    echo "      x86 rt object id =  $id"
    echo ""
    echo "fn :: x86 rt hex value Int => Int"
    echo "      x86 rt hex value c"
    echo "        | c <= 57 = c - 48"
    echo "        | otherwise = c - 87"
    echo ""
    echo "fn :: x86 rt hex chunk String Int Int [Int] => [Int]"
    echo "      x86 rt hex chunk s pos end acc"
    echo "        | pos >= end = acc"
    echo "        | otherwise = x86 rt hex chunk s (pos + 2) end (acc :: [((x86 rt hex value (str char at s pos)) * 16) + (x86 rt hex value (str char at s (pos + 1)))])"
    echo ""
    echo "fn :: x86 rt hex range String Int Int => [Int]"
    echo "      x86 rt hex range s start end"
    echo "        | (end - start) <= 64 = x86 rt hex chunk s start end []"
    echo "        | otherwise ="
    echo "          mid = start + (((end - start) / 4) * 2)"
    echo "          (x86 rt hex range s start mid) :: (x86 rt hex range s mid end)"
    echo ""
    echo "fn :: x86 rt object bytes => [Int]"
    echo "      x86 rt object bytes =  x86 rt concat (map (l => x86 rt hex range l 0 (str len l)) (x86 rt object hex))"
    echo ""
    echo "fn :: x86 rt concat [[Int]] => [Int]"
    echo "      x86 rt concat []     =  []"
    echo "      x86 rt concat (x:xs) =  x :: (x86 rt concat xs)"
    echo ""
    echo "fn :: x86 rt object hex => [String]"
    printf '      x86 rt object hex =  ['
    printf '%s]\n' "$(od -An -tx1 -v "$out" | tr -d ' \n' | fold -w 4096 | sed 's/.*/"&"/' | paste -sd, - | sed 's/,/, /g')"
  } > "$mod"
  echo "wrote $mod ($size bytes of object)"
fi
if [ "$flat" = yes ]; then
  base=4198848   # 0x4011c0: the jump table of 56 slots of 8 bytes comes first, at 0x401000
  cat > "$tmp/flat.lds" <<LDS
ENTRY(_start)
SECTIONS {
  . = $base;
  .text : ALIGN(16) { *(.text .text.*) }
  .rodata : ALIGN(16) { *(.rodata .rodata.*) }
  .data : ALIGN(16) { *(.data .data.*) }
  .bss : ALIGN(64) { *(.bss .bss.* COMMON) }
  /DISCARD/ : { *(.note*) *(.eh_frame*) *(.comment*) }
}
LDS
  ld -n --no-warn-rwx-segments -T "$tmp/flat.lds" "$out" -o "$tmp/flat.elf"
  objcopy -O binary --set-section-flags .bss=alloc,load,contents "$tmp/flat.elf" "$tmp/flat.bin"
  mod=src/main/ridgun/lib/x86flat.ridgun
  size=$(wc -c < "$tmp/flat.bin")
  id=$(cksum < "$tmp/flat.bin" | cut -d' ' -f1)
  addr() { printf '%d' "0x$(nm "$tmp/flat.elf" | awk -v n="$1" '$3 == n { print $1 }')"; }
  {
    echo "-- ============================================================"
    echo "-- src/main/ridgun/lib/x86flat.ridgun"
    echo "-- GENERATED by src/main/runtime/build-linux-x86_64.sh --flat from"
    echo "-- src/main/runtime/ (ADR-0013). Do not edit: change the IR and run the"
    echo "-- script again."
    echo "-- The runtime for Linux on x86-64 linked at $base ($size bytes, its"
    echo "-- .bss included) for the pure x86-64 encoder, in hex, and the address"
    echo "-- of each entry point the encoder calls."
    echo "-- ============================================================"
    echo ""
    echo "import x86rt"
    echo ""
    echo "fn :: x86 flat id => Int"
    echo "      x86 flat id =  $id"
    echo ""
    echo "fn :: x86 flat base => Int"
    echo "      x86 flat base =  $base"
    echo ""
    echo "fn :: x86 flat start => Int"
    echo "      x86 flat start =  $(addr _start)"
    echo ""
    echo "-- The address of the IR function behind slot n of the jump table."
    echo "fn :: x86 flat slot target Int => Int"
    n=0
    for name in init_frame epilogue tco_copy clear_locals clone_slot drop_val cmm_move store_slot rebind_slot cmm_drop_slot load_real_lit load_str_lit load_adt0 make_adt make_list make_tuple make_tensor str_interp pack_seq as_bool match_int match_real match_str match_bool match_empty match_nonempty list_head list_tail match_tuple tuple_get match_adt adt_field adt_set bool_inv out echo bin_op index index_set seq_select einsum hadamard - - - - enter_region exit_region - - - - call_indirect1 call_indirect2 builtin; do
      n=$((n + 1))
      if [ "$name" != "-" ]; then
        echo "      x86 flat slot target $n =  $(addr __rg_rt_$name)"
      fi
    done
    echo "      x86 flat slot target _ =  0"
    echo ""
    echo "-- Entry points the hand-assembled routines of the encoder call by address."
    echo "fn :: x86 flat symbol Int => Int"
    k=0
    for name in alloc_buf box_rc_vec box_rval pop_i64 alloc_str drop_slot pal_dispatch ext; do
      k=$((k + 1))
      echo "      x86 flat symbol $k =  $(addr __rg_rt_$name)"
    done
    echo "      x86 flat symbol _ =  0"
    echo ""
    echo "fn :: x86 flat bytes => [Int]"
    echo "      x86 flat bytes =  x86 rt concat (map (l => x86 rt hex range l 0 (str len l)) (x86 flat hex))"
    echo ""
    echo "fn :: x86 flat hex => [String]"
    printf '      x86 flat hex =  ['
    printf '%s]\n' "$(od -An -tx1 -v "$tmp/flat.bin" | tr -d ' \n' | fold -w 4096 | sed 's/.*/"&"/' | paste -sd, - | sed 's/,/, /g')"
  } > "$mod"
  echo "wrote $mod ($size bytes of image)"
fi
echo "wrote $out"
